#!/usr/bin/env node
// T155.9: deterministic generation of `src/shared/supabase/database-types.ts`
// from the local Supabase stack's `api` schema. Modeled on
// supabase/tests/run-db-tests.mjs's style: one PASS/FAIL line per step,
// full output on failure, single non-zero exit on any failure.
//
// Usage:
//   node supabase/scripts/generate-database-types.mjs            # write
//   node supabase/scripts/generate-database-types.mjs --check    # verify no drift
//   yarn db:generate-types
//   yarn db:generate-types -- --check
//
// Determinism requires generating from a *clean* local stack: `supabase db
// reset` always runs first (never generate from a stack with ad hoc manual
// changes), and a cleanup `db reset` always runs last, regardless of
// outcome, so this command never leaves the stack dirty for whatever runs
// next.

import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SUPABASE = ['npx', '--yes', 'supabase@2.115.0'];

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..', '..');
const OUTPUT_PATH = path.join(REPO_ROOT, 'src', 'shared', 'supabase', 'database-types.ts');

const BANNER =
  '// Generated by `yarn db:generate-types` — do not hand-edit.\n' +
  '// Source: supabase/migrations/. Run `yarn db:generate-types` after any\n' +
  '// migration change.\n\n';

function run(name, argv, options = {}) {
  const started = Date.now();
  const proc = spawnSync(argv[0], argv.slice(1), {
    encoding: 'utf8',
    shell: false,
    maxBuffer: 128 * 1024 * 1024,
    cwd: REPO_ROOT,
    env: { ...process.env, CI: '1' },
    ...options,
  });
  const seconds = ((Date.now() - started) / 1000).toFixed(1);
  const code = proc.status === null ? 1 : proc.status;
  process.stdout.write(`${code === 0 ? 'PASS' : 'FAIL'}  ${name.padEnd(28)}${seconds}s\n`);
  if (code !== 0) {
    const output = `${proc.stdout ?? ''}${proc.stderr ?? ''}`;
    process.stdout.write(`\n--- \`${argv.join(' ')}\` (exit ${code}) ---\n${output.trim()}\n\n`);
  }
  return { name, code, stdout: proc.stdout ?? '', stderr: proc.stderr ?? '' };
}

function generateTypesContent(manageLifecycle) {
  if (manageLifecycle) {
    const start = run('supabase start', [...SUPABASE, 'start']);
    if (start.code !== 0) return { code: start.code, content: null };

    const reset = run('db reset', [...SUPABASE, 'db', 'reset']);
    if (reset.code !== 0) return { code: reset.code, content: null };
  }

  const genTypes = run('gen types typescript', [
    ...SUPABASE,
    'gen',
    'types',
    'typescript',
    '--local',
    '--schema',
    'api',
  ]);
  if (genTypes.code !== 0) return { code: genTypes.code, content: null };

  return { code: 0, content: BANNER + genTypes.stdout };
}

function main() {
  const args = process.argv.slice(2);
  const checkMode = args.includes('--check');
  const reuseCurrentDatabase = args.includes('--reuse-current-database');
  const unknown = args.filter((arg) => arg !== '--check' && arg !== '--reuse-current-database');
  if (unknown.length > 0) {
    process.stderr.write(`unrecognized argument(s): ${unknown.join(', ')}\n`);
    process.exit(2);
  }
  if (reuseCurrentDatabase && !checkMode) {
    process.stderr.write('--reuse-current-database is only valid with --check\n');
    process.exit(2);
  }

  // The consolidated database suite has already started and reset the stack,
  // so its drift check reuses that exact schema. Standalone invocations retain
  // the safer self-contained start/reset/cleanup lifecycle.
  const manageLifecycle = !reuseCurrentDatabase;
  const { code, content } = generateTypesContent(manageLifecycle);

  let finalCode = code;

  if (code === 0 && content !== null) {
    if (checkMode) {
      const tmpDir = mkdtempSync(path.join(tmpdir(), 'daily-dama-db-types-'));
      const tmpFile = path.join(tmpDir, 'database-types.ts');
      writeFileSync(tmpFile, content, 'utf8');

      let existing;
      try {
        existing = readFileSync(OUTPUT_PATH, 'utf8');
      } catch {
        existing = null;
      }

      if (existing === content) {
        process.stdout.write(`PASS  ${'types drift check'.padEnd(28)}0.0s\n`);
      } else {
        process.stdout.write(`FAIL  ${'types drift check'.padEnd(28)}0.0s\n`);
        process.stdout.write(
          `\n--- checked-in ${path.relative(REPO_ROOT, OUTPUT_PATH)} does not match freshly-generated output ---\n` +
            'Run `yarn db:generate-types` (without --check) to regenerate and commit the result.\n' +
            (existing === null
              ? `${path.relative(REPO_ROOT, OUTPUT_PATH)} does not exist yet.\n`
              : `Freshly generated output written to: ${tmpFile}\n` +
                `Diff with: diff ${JSON.stringify(OUTPUT_PATH)} ${JSON.stringify(tmpFile)}\n`) +
            '\n',
        );
        finalCode = 1;
      }

      rmSync(tmpDir, { recursive: true, force: true });
    } else {
      writeFileSync(OUTPUT_PATH, content, 'utf8');
      process.stdout.write(`PASS  ${'write database-types.ts'.padEnd(28)}0.0s\n`);
    }
  }

  // Standalone runs own cleanup. When nested in test:db, the outer harness
  // owns the unconditional cleanup reset and must be allowed to report it.
  const cleanup = manageLifecycle ? run('cleanup db reset', [...SUPABASE, 'db', 'reset']) : null;

  if (finalCode !== 0) {
    process.stdout.write(`\nGENERATE DATABASE TYPES: FAIL\n`);
    process.exit(finalCode || 1);
  }
  if (cleanup && cleanup.code !== 0) {
    process.stdout.write('\nGENERATE DATABASE TYPES: FAIL — succeeded but the final cleanup `db reset` failed\n');
    process.exit(cleanup.code || 1);
  }
  process.stdout.write(`\nGENERATE DATABASE TYPES: PASS${checkMode ? ' (no drift)' : ''}\n`);
  process.exit(0);
}

main();
