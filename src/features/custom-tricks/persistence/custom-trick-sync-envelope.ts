// T157.5: the custom-tricks domain's sync bookkeeping envelope -- a second,
// parallel identity-scoped domain instance alongside the primary
// `customTrickReducer` (src/features/custom-tricks/model/custom-trick.ts),
// not a replacement for it. Mirrors `profile-sync-envelope.ts` structurally
// (T157.4); see `.claude/plans/T157.5.md` for the full design. The primary
// reducer stays the sole source of truth for the live `CustomTrickCollection`
// shown in the UI; this file only tracks "what has this device told the
// server, and what does it still owe the server."
//
// Simpler than the profile envelope in one way: `api.custom_tricks` is a
// single row type (no scalar/child-table split), so there is no
// `profileRevision`-equivalent scalar field here -- only a per-trick
// revision map.

import { isCustomTrickCollection } from '@/features/custom-tricks/persistence/custom-trick-persistence';
import type { CustomTrickCollection } from '@/features/custom-tricks/model/custom-trick';
import type { Identity } from '@/shared/persistence/identity';
import type {
  KeyValueStorage,
  PersistenceLoadResult,
  PersistenceSaveResult,
} from '@/shared/persistence/storage';
import type { NewOutboxOperationInput } from '@/shared/sync/outbox-operation';
import {
  acknowledgeOutboxOperation,
  loadSyncEnvelope,
  recordOutboxOperationAttempt,
  replacePendingOperationForRecord,
  saveSyncEnvelope,
  updateSyncCursor,
  type SyncEnvelope,
  type SyncEnvelopeCodec,
} from '@/shared/sync/sync-envelope';

export interface CustomTrickSyncSnapshot {
  // Mirror of the primary reducer's state at the moment of the last envelope
  // mutation -- kept here (rather than re-derived) so the envelope is a
  // fully self-contained, independently reloadable document.
  readonly collection: CustomTrickCollection;
  readonly trickRevisions: Readonly<Record<string, number>>;
}

export function createInitialCustomTrickSyncSnapshot(collection: CustomTrickCollection): CustomTrickSyncSnapshot {
  return { collection, trickRevisions: {} };
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function isRevisionNumber(value: unknown): value is number {
  return typeof value === 'number' && Number.isInteger(value) && value >= 1;
}

function isTrickRevisions(value: unknown): value is Readonly<Record<string, number>> {
  if (!isRecord(value)) return false;
  return Object.values(value).every(isRevisionNumber);
}

export function isCustomTrickSyncSnapshot(value: unknown): value is CustomTrickSyncSnapshot {
  if (!isRecord(value)) return false;

  const { collection, trickRevisions } = value;
  if (!isCustomTrickCollection(collection)) return false;
  if (!isTrickRevisions(trickRevisions)) return false;

  return true;
}

export const customTrickSyncSnapshotCodec: SyncEnvelopeCodec<CustomTrickSyncSnapshot> = {
  isState: isCustomTrickSyncSnapshot,
};

export const CUSTOM_TRICK_SYNC_ENVELOPE_STORAGE_KEY = 'daily-dama:custom-trick-sync-envelope';

export async function loadCustomTrickSyncEnvelope(
  storage: KeyValueStorage,
  identity: Identity,
  initialSnapshot: CustomTrickSyncSnapshot,
): Promise<PersistenceLoadResult<SyncEnvelope<CustomTrickSyncSnapshot>>> {
  return loadSyncEnvelope(
    storage,
    CUSTOM_TRICK_SYNC_ENVELOPE_STORAGE_KEY,
    'customTricks',
    customTrickSyncSnapshotCodec,
    identity,
    initialSnapshot,
  );
}

export async function saveCustomTrickSyncEnvelope(
  storage: KeyValueStorage,
  envelope: SyncEnvelope<CustomTrickSyncSnapshot>,
): Promise<PersistenceSaveResult> {
  return saveSyncEnvelope(storage, CUSTOM_TRICK_SYNC_ENVELOPE_STORAGE_KEY, envelope);
}

export type CustomTrickSyncEnvelopeAction =
  | { readonly type: 'envelopeRestored'; readonly envelope: SyncEnvelope<CustomTrickSyncSnapshot> }
  | {
      readonly type: 'localMutationApplied';
      readonly identity: Identity;
      readonly now: number;
      readonly nextSnapshot: CustomTrickSyncSnapshot;
      readonly operationInputs: readonly NewOutboxOperationInput[];
      // One id per operationInput, pre-generated by the caller -- no
      // Math.random()/Date.now() inside this reducer.
      readonly operationIds: readonly string[];
    }
  | { readonly type: 'operationAcknowledged'; readonly identity: Identity; readonly operationId: string }
  | {
      readonly type: 'operationAttemptRecorded';
      readonly identity: Identity;
      readonly operationId: string;
      readonly attemptedAt: number;
      readonly errorMessage: string | null;
    }
  // Dispatched after a successful push (revision returned by the server) or
  // a safe pull-adopt (outbox empty, revision cache refreshed from pulled
  // rows). Carries a full replacement snapshot -- the caller computes it.
  | { readonly type: 'revisionRecorded'; readonly snapshot: CustomTrickSyncSnapshot }
  | {
      readonly type: 'cursorUpdated';
      readonly identity: Identity;
      readonly cursor: string | null;
      readonly updatedAt: number;
    };

export function customTrickSyncEnvelopeReducer(
  state: SyncEnvelope<CustomTrickSyncSnapshot>,
  action: CustomTrickSyncEnvelopeAction,
): SyncEnvelope<CustomTrickSyncSnapshot> {
  switch (action.type) {
    case 'envelopeRestored':
      return action.envelope;

    case 'localMutationApplied': {
      if (action.operationInputs.length !== action.operationIds.length) {
        // Caller contract violation -- treat as a no-op rather than silently
        // dropping/misaligning operations against ids.
        return state;
      }

      let next = state;
      for (let index = 0; index < action.operationInputs.length; index += 1) {
        const operationInput = action.operationInputs[index];
        const operationId = action.operationIds[index];
        // Every operation in this batch targets the *final* nextSnapshot's
        // state -- only the first call actually swaps `state`; subsequent
        // calls in the same batch pass the same nextSnapshot again, which
        // is a harmless no-op re-assignment of an already-current value.
        const result = replacePendingOperationForRecord(
          next,
          action.identity,
          action.nextSnapshot,
          operationInput,
          action.now,
          operationId,
        );
        if (result.status !== 'applied') return state; // reject the whole batch atomically
        next = result.envelope;
      }
      return next;
    }

    case 'operationAcknowledged': {
      const result = acknowledgeOutboxOperation(state, action.identity, action.operationId);
      return result.status === 'applied' ? result.envelope : state;
    }

    case 'operationAttemptRecorded': {
      const result = recordOutboxOperationAttempt(
        state,
        action.identity,
        action.operationId,
        action.attemptedAt,
        action.errorMessage,
      );
      return result.status === 'applied' ? result.envelope : state;
    }

    case 'revisionRecorded':
      return { ...state, state: action.snapshot };

    case 'cursorUpdated': {
      const result = updateSyncCursor(state, action.identity, action.cursor, action.updatedAt);
      return result.status === 'applied' ? result.envelope : state;
    }
  }
}
